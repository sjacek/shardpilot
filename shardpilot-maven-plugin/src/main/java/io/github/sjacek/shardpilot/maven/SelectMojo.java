package io.github.sjacek.shardpilot.maven;

import io.github.sjacek.shardpilot.TestSelection;
import io.github.sjacek.shardpilot.ShardPlan;
import java.util.Set;

import io.github.sjacek.shardpilot.ClassManifest;
import io.github.sjacek.shardpilot.ShardManifests;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.TreeSet;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugin.MojoFailureException;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;

/**
 * Writes native exclusions and pre-worker evidence; never regenerates downloaded planning files.
 * Bind before the selected native runner. Eligibility/history/index are validated before writing,
 * and actual evidence is written only after the generated exclusions have been saved. The manifest
 * describes allowed candidates, not execution success, so it survives ordinary test failures.
 */
@Mojo(name = "select", defaultPhase = LifecyclePhase.PROCESS_TEST_CLASSES, threadSafe = true)
public final class SelectMojo extends AbstractShardMojo {
    /** Creates the container-managed native-selection goal. */
    public SelectMojo() { }

    @Override
    public void execute() throws MojoExecutionException, MojoFailureException {
        if (skipAggregator()) return;
        try {
            var candidates = new RunnerConfiguration(this).scan();
            var explicit = explicitSelection(candidates.eligible());
            String history = history();
            Set<String> selected;
            if (explicit == null) selected = ShardManifests.select(candidates.eligible(), history, shardCount, shardIndex);
            else {
                ShardPlan.validateShard(shardCount, shardIndex);
                var plan = ShardPlan.create(
                        TestSelection.history(history, explicit.selected()), shardCount);
                selected = new TreeSet<>();
                for (String name : explicit.selected()) if (plan.shardFor(name) == shardIndex) selected.add(name);
                explicit.write(namespace().resolve("selection"), history, shardCount);
            }
            var excluded = new TreeSet<>(candidates.all());
            // Deny unselected helpers as well as other eligible tests: native defaults must not widen S.
            excluded.removeAll(selected);
            var lines = new ArrayList<String>();
            lines.add("# Generated by ShardPilot; use a separate namespace per runner/project.");
            lines.add("**/module-info.class");
            lines.add("**/package-info.class");
            for (String name : excluded) lines.add(RunnerConfiguration.classFile(name));
            // Deny every class for an empty shard, including native defaults after an empty include list.
            if (selected.isEmpty()) lines.add("**/*");
            Files.createDirectories(exclusions().toAbsolutePath().getParent());
            Files.write(exclusions(), lines, StandardCharsets.UTF_8);
            ClassManifest.write(selectionDirectory().resolve("actual-" + shardIndex + ".yaml"), selected);
            var identity = selectionDirectory().resolve("selection-" + shardIndex + ".id");
            if (explicit == null) Files.deleteIfExists(identity);
            else Files.writeString(identity, explicit.identity(history, shardCount), StandardCharsets.UTF_8);
            getLog().info("ShardPilot actual selection: shard " + shardIndex + ", " + selected.size() + " classes");
        } catch (IllegalArgumentException exception) {
            throw new MojoFailureException(exception.getMessage(), exception);
        } catch (IOException exception) {
            throw new MojoExecutionException("Cannot record ShardPilot selection", exception);
        }
    }
}
